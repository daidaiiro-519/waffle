    d = ' stroke-dasharray="5 4"' if dash else ""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" '
            f'fill="var({P["card"]})" stroke="var({P[stroke]})" stroke-width="1.4"{d}/>')


