def run(*a):
    r = subprocess.run(["uv", "run", "waffle", *a], capture_output=True, text=True, cwd=CWD)
    return (r.stdout or r.stderr).strip()


def walk(nodes, path=()):
    for n in nodes:
        here = path + (n["name"],)
        if "figure" in n:
            yield " > ".join(here), n["figure"]
        yield from walk(n.get("children", []), here)


for doc in ("subdomain", "bounded-context", "domain-model", "business-logic-simple",
            "evolving-design", "ubiquitous-language"):
    p = f".waffle/documents/knowledge/{doc}." + "json"
    items = json.loads(run("query", "--operation", "query_path", "--path", p,
                           "--blockKey", "nodes", "--expression", "items"))["value"]
    hit = 0
    for path, fig in walk(items):
        rows = NOTES.get((doc, path))
        if not rows:
            print(f"  !! 注釈の当てが無い: {doc} / {path}")
            continue
        fig["notes"] = [{"anchor": a, "note": n} for a, n in rows]
        hit += 1
    run("scaffold", "--operation", "fill", "--path", p,
        "--values", json.dumps({"content.nodes.items": items}, ensure_ascii=False))
    print(f"{doc}: 図{hit}件へ注釈を入れた / "
          f"{run('validate', '--path', p)[:80]}")
    run("render", "--path", p)
