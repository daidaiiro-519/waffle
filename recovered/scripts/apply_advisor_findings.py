for d in (C1, C2):
    r = subprocess.run(["uv", "run", "waffle", "validate", "--path", f"{ROOT}/{d}.json"],
                       capture_output=True, text=True, cwd=CWD)
    print(f"[validate {d}] {(r.stdout or r.stderr).strip()[:160]}")
