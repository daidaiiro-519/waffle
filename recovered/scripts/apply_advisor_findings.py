"""助言役の検証結果を、2件のknowledge候補へ取り込む。

候補1へは、文脈の段の言明の性質と、段の数が実装方法に依存する点を足す。
候補2へは、被覆が接地の代わりにならない点を足す。
"""
from __future__ import annotations

import json
import subprocess

CWD = "/home/daidaiiro/workspace/waffle"
ROOT = ".waffle/documents/knowledge"
C1 = "knowledge-cand-operation-contract-closes-invariants"
C2 = "knowledge-cand-binding-differs-by-composition-level"


def q(doc_id: str, block: str, expr: str):
    r = subprocess.run(
        ["uv", "run", "waffle", "query", "--operation", "query_path",
         "--path", f"{ROOT}/{doc_id}.json", "--blockKey", block, "--expression", expr],
        capture_output=True, text=True, cwd=CWD)
    return json.loads(r.stdout)["value"]


def fill(doc_id: str, values: dict) -> None:
    r = subprocess.run(
        ["uv", "run", "waffle", "scaffold", "--operation", "fill",
         "--path", f"{ROOT}/{doc_id}.json",
         "--values", json.dumps(values, ensure_ascii=False)],
        capture_output=True, text=True, cwd=CWD)
    print(f"[{doc_id}] {(r.stdout or r.stderr).strip()[:220]}")


# ============================================================ 候補1

p1 = q(C1, "principles", "items")
p1 += [
    "段の受け入れ基準は、段によって言明の種類が違う。"
    "集約の不変条件が状態空間についての全称命題であるのに対し、"
    "境界づけられたコンテキストの受け入れ基準は意味と分担についての全称命題である"
    "（この境界の内側で語がそれぞれ一つの意味を持つ／同じデータへの一連の操作が境界の外へ分散していない／"
    "外部へ公開する契約と外部モデルを取り込む際の変換）。",

    "この違いは、破ったときに起きることの違いとして現れる。"
    "集約の不変条件は実行時に検出でき、操作が失敗する。"
    "コンテキストの受け入れ基準は実行時には何も起きず、動き続けたままモデルが実態から乖離する。"
    "修復も前者は実装を直すだけだが、後者は境界を引き直す。",

    "したがってコンテキストの段の受け入れ基準は、機能要件の形式では書けない。"
    "機能要件として書こうとすると、必ず下の段の内容が上へ複写され、コンテキストの段が目次に退化する。",

    "段の数は業務領域の実装方法に依存する。"
    "集約と不変条件を持たない実装方法を採る領域では集約の段が存在せず、梯子は2段になる。"
    "段の数を全域で固定した宣言形式は、この差を表現できない。",

    "語彙は、この梯子の前提であって梯子の一部ではない。"
    "各段の基準も振る舞いも、境界の内側で一貫した意味を持つ言葉の上に書かれる。",
]
fill(C1, {"content.principles.items": p1})

a1 = q(C1, "antiPatterns", "items")
a1 += [
    {"name": "コンテキストの段に機能要件を書ける欄を与える",
     "problem": "下の段の内容が上へ複写され、コンテキストの段が単なる目次に退化して、"
                "意味と分担についての言明を置く場所が失われる。"},
    {"name": "段の数を全域で固定する",
     "problem": "集約を持たない実装方法の領域でも3段を強い、空の段を埋めるための形だけの宣言が生まれる。"},
]
fill(C1, {"content.antiPatterns.items": a1})

fill(C1, {
    "content.provenance.caveats":
        "この規律は業務領域の分類（中核・一般・補完）に依存せず、すべてに適用されるものとして述べている。"
        "主張の芯は「状態を変える経路が閉じていれば全称命題を有限のコマンド集合へ分配できる」という構造についてのもので、"
        "領域の複雑さで成否が変わる性質のものではない。\n\n"
        "未検証の留保が4点ある。\n"
        "(1) 段の数が実装方法に依存する点を、宣言としてどう表現するかが未定。"
        "集約を持たない実装方法の領域では梯子が2段になるが、"
        "「段が無い」と「段を書き忘れた」をどう区別するかは決まっていない。"
        "この論点は業務領域の分類（どの実装方法を採るか）と結び付いており、"
        "『サブドメインは契約の段ではない』としてサブドメインを構造から外しただけでは片付かない。\n"
        "(2) 実際に当てはめて確かめた業務領域が、いまのところ補完（supporting）と分類されたもの1件しかない。"
        "これは適用範囲の限界ではなく実例の偏りだが、中核（core）の業務領域で一度確かめる必要がある。\n"
        "(3) コマンド数と不変条件数の掛け算が、中核領域の規模で現実的な大きさに収まるかは未実測。\n"
        "(4) 「情報の不在」を主張する規則の一覧（秘密の非保持・消去の完全性・追記専用性・保持期限）が"
        "この族を尽くしているかは確かめていない。\n\n"
        "なお検証の過程で、「中核領域はピラミッド形のテスト方針をとるため、"
        "不変条件を受け入れ基準へ寄せるとテスト方針の経験則と衝突する」という異議が出たが、これは採らなかった。"
        "この異議は「どこで宣言するか」と「どの層で検証するか」を混ぜている。"
        "コマンドへ分配した基準を単体テストで厚く検証することは矛盾なくできるため、"
        "分配（宣言の話）とピラミッド（検証層の話）は両立する。",
})


