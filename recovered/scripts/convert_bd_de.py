def run(*a):
    r = subprocess.run(["uv", "run", "waffle", *a], capture_output=True, text=True, cwd=CWD)
    return (r.stdout or r.stderr).strip()


def n(name, kind, summary, *, src=None, figure=None, verbatim=None, children=None):
    d = {"name": name, "kind": kind, "summary": summary}
    for k, v in (("sourceRef", src), ("figure", figure), ("verbatim", verbatim),
                 ("children", children)):
        if v:
            d[k] = v
    return d


def e(f, t, label=None):
    d = {"from": f, "to": t}
    if label:
        d["label"] = label
    return d


def fig(intent, reading, nodes, edges, *, direction="TD", groups=(), notes=()):
    return {"intent": intent, "reading": reading, "direction": direction,
            "groups": [{"label": g, "nodes": ns} for g, ns in groups],
            "nodes": list(nodes), "edges": edges,
            "notes": [{"anchor": a, "note": t} for a, t in notes]}


def table(intent, reading, source):
    return {"intent": intent, "reading": reading, "lang": "markdown", "source": source}


def apply(path, vals):
    run("scaffold", "--operation", "migrate_schema", "--path", path,
        "--schemaRef", "KnowledgeSchema/v6")
    for old in ("principles", "classifications", "decisionCriteria", "examples",
                "antiPatterns"):
        run("scaffold", "--operation", "clear_field", "--path", path,
            "--fieldPath", f"content.{old}")
    print(run("scaffold", "--operation", "fill", "--path", path,
              "--values", json.dumps(vals, ensure_ascii=False))[:110])
    print(run("validate", "--path", path)[:200])
    print(run("render", "--path", path)[:90])


